#!/usr/bin/env python3
"""Safe cleanup of unnecessary, unwanted and duplicate files. Reversible.

  python3 cleanup.py                 dry run: lists candidates, writes results/cleanup_candidates.csv
  python3 cleanup.py --apply         moves candidates into .trash/<timestamp>/ and writes results/cleanup_manifest.csv
  python3 cleanup.py --restore TS    moves everything from .trash/TS/ back where it came from
  python3 cleanup.py --purge         permanently deletes .trash/ (run deliberately, nothing else does)

NEVER a candidate:
  - files tracked by git
  - anything under results/ mutants/ tasks/ checks/ logs/ rtl/ formal/ tb/ sweep_work/ .git/ .done/ .trash/
  - the kit's own scripts, STATE.md, CLAUDE.md, README.md
  - any path cited in results/summary.json, results/*.md, STATE.md or results/evidence/INDEX.txt

Candidates (untracked, uncited, outside the protected folders):
  junk       Windows Zone.Identifier files, *.tmp, *~, *.swp, *.pyc, __pycache__, .DS_Store, Thumbs.db, nohup.out
  workdir    SymbiYosys work directories (they contain model/ and src/); regenerated by sby
  scratch    triage/ (scratch copies made by triage_c03.sh)
  duplicate  a file byte-identical to a protected file
  empty      empty files and empty folders
Duplicates with NO protected twin are listed as REVIEW and never moved.
"""
import csv
import glob
import hashlib
import os
import re
import shutil
import subprocess
import sys
import time

ROOT = os.getcwd()
PROTECT_DIRS = {".git", "results", "mutants", "tasks", "checks", "rtl", "formal", "tb",
                "logs", ".done", ".trash", "sweep_work"}
PROTECT_FILES = {"STATE.md", "CLAUDE.md", "README.md", "driver.sh", "run_quiet.sh",
                 "triage_c03.sh", "collect_evidence.sh", "cleanup.py", "sweep.sh",
                 "plot_sweep.py", ".driver.lock", ".gitignore"}
JUNK_GLOBS = ["*:Zone.Identifier", "*.tmp", "*~", "*.swp", "*.pyc"]
JUNK_NAMES = {".DS_Store", "Thumbs.db", "nohup.out"}
JUNK_DIRS = {"__pycache__"}
SCRATCH_DIRS = {"triage", "c03_verify"}
MAX_HASH_BYTES = 200 * 1024 * 1024


def norm(p):
    return p.replace(os.sep, "/").lstrip("./") if p != "." else "."


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def dir_size(path):
    total = 0
    for dp, _, fns in os.walk(path):
        for fn in fns:
            try:
                total += os.path.getsize(os.path.join(dp, fn))
            except OSError:
                pass
    return total


def git_tracked():
    try:
        out = subprocess.run(["git", "ls-files", "-z", "--", "."], capture_output=True, cwd=ROOT)
        if out.returncode != 0:
            return None
        return {norm(p) for p in out.stdout.decode("utf-8", "replace").split("\0") if p}
    except FileNotFoundError:
        return None


def cited_paths():
    texts = []
    for p in ["results/summary.json", "STATE.md"] + glob.glob("results/*.md"):
        if os.path.isfile(p):
            texts.append(open(p, errors="replace").read())
    toks = set()
    for t in texts:
        toks |= set(re.findall(r"[A-Za-z0-9_.\-]+(?:/[A-Za-z0-9_.\-]+)+", t))
    idx = "results/evidence/INDEX.txt"
    if os.path.isfile(idx):
        for line in open(idx, errors="replace"):
            parts = line.rstrip("\n").split("  ", 1)
            if len(parts) == 2:
                toks.add(parts[1].strip())
    return {t.lstrip("./") for t in toks}


def make_is_cited(toks):
    def is_cited(rel):
        for t in toks:
            if t == rel or t.endswith("/" + rel) or t.startswith(rel + "/") or ("/" + rel + "/") in t:
                return True
        return False
    return is_cited


def scan():
    tracked = git_tracked()
    tracked_set = tracked or set()
    is_cited = make_is_cited(cited_paths())

    def tracked_under(rel):
        return rel in tracked_set or any(t.startswith(rel + "/") for t in tracked_set)

    cands, untracked_files = [], []   # cands: (category, rel, reason, is_dir)
    protected_files = []              # paths whose content counts as the canonical twin

    for dp, dns, fns in os.walk(ROOT, topdown=True):
        rel_dir = norm(os.path.relpath(dp, ROOT))
        keep = []
        for d in sorted(dns):
            rel = norm(os.path.join(rel_dir, d)) if rel_dir != "." else d
            full = os.path.join(dp, d)
            if os.path.islink(full):
                continue
            top = rel.split("/")[0]
            if top in PROTECT_DIRS and rel_dir == ".":
                for pdp, _, pfns in os.walk(full):
                    for pfn in pfns:
                        protected_files.append(os.path.join(pdp, pfn))
                continue
            if tracked_under(rel) or is_cited(rel):
                keep.append(d)          # protected dir: descend to find junk only if fully untracked? no: skip
                for pdp, _, pfns in os.walk(full):
                    for pfn in pfns:
                        protected_files.append(os.path.join(pdp, pfn))
                keep.pop()
                continue
            if d in JUNK_DIRS:
                cands.append(("junk", rel, "junk folder", True)); continue
            if d in SCRATCH_DIRS and rel_dir == ".":
                cands.append(("scratch", rel, "scratch folder from triage_c03.sh", True)); continue
            subs = set(os.listdir(full))
            if "model" in subs and "src" in subs:
                cands.append(("workdir", rel, "SymbiYosys work directory, untracked and uncited", True)); continue
            if not subs:
                cands.append(("empty", rel, "empty folder", True)); continue
            keep.append(d)
        dns[:] = keep

        for fn in sorted(fns):
            rel = norm(os.path.join(rel_dir, fn)) if rel_dir != "." else fn
            full = os.path.join(dp, fn)
            if os.path.islink(full):
                continue
            if rel_dir == "." and fn in PROTECT_FILES:
                protected_files.append(full); continue
            if rel in tracked_set or is_cited(rel):
                protected_files.append(full); continue
            if fn in JUNK_NAMES or any(__import__("fnmatch").fnmatch(fn, g) for g in JUNK_GLOBS):
                cands.append(("junk", rel, "junk file", False)); continue
            try:
                size = os.path.getsize(full)
            except OSError:
                continue
            if size == 0 and fn != ".gitkeep":
                cands.append(("empty", rel, "empty file", False)); continue
            untracked_files.append((rel, full, size))

    # duplicates: hash only files whose size matches an untracked candidate
    sizes = {s for _, _, s in untracked_files if 0 < s <= MAX_HASH_BYTES}
    canon = {}
    for pf in protected_files:
        try:
            s = os.path.getsize(pf)
        except OSError:
            continue
        if s in sizes:
            canon.setdefault(sha256(pf), pf)
    groups = {}
    for rel, full, size in untracked_files:
        if size == 0 or size > MAX_HASH_BYTES:
            continue
        h = sha256(full)
        if h in canon:
            cands.append(("duplicate", rel, "identical to protected file " + norm(os.path.relpath(canon[h], ROOT)), False))
        else:
            groups.setdefault(h, []).append(rel)
    review = [v for v in groups.values() if len(v) > 1]
    return cands, review, tracked is not None


def describe(rel, is_dir):
    full = os.path.join(ROOT, rel)
    if is_dir:
        return dir_size(full), ""
    size = os.path.getsize(full)
    return size, (sha256(full) if size <= MAX_HASH_BYTES else "")


def top_most(cands):
    dirs = [rel for _, rel, _, d in cands if d]
    out = []
    for c in cands:
        rel = c[1]
        if any(rel != d and rel.startswith(d + "/") for d in dirs):
            continue
        out.append(c)
    return out


def main():
    args = sys.argv[1:]
    if args[:1] == ["--purge"]:
        shutil.rmtree(".trash", ignore_errors=True)
        print("purged .trash/"); return
    if args[:1] == ["--restore"]:
        ts = args[1]; base = os.path.join(".trash", ts); n = 0
        for dp, dns, fns in os.walk(base):
            for name in fns + [d for d in dns if not os.listdir(os.path.join(dp, d))]:
                src = os.path.join(dp, name); rel = os.path.relpath(src, base); dst = os.path.join(ROOT, rel)
                if os.path.exists(dst):
                    print("skip (exists):", rel); continue
                os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.move(src, dst); n += 1
        print(f"restored {n} items from {base}"); return

    apply = "--apply" in args
    cands, review, is_git = scan()
    cands = top_most(cands)
    os.makedirs("results", exist_ok=True)
    rows = []
    for cat, rel, reason, is_dir in cands:
        size, digest = describe(rel, is_dir)
        rows.append((cat, rel, reason, size, digest))
    if not is_git:
        print("WARNING: not a git repo or git missing. Only folder/citation protection applies. Make a backup first.")

    counts = {}
    for r in rows:
        counts[r[0]] = counts.get(r[0], 0) + 1
    total = sum(r[3] for r in rows)
    print(f"candidates: {len(rows)}  ({total/1048576:.1f} MB)  by category: {counts or 'none'}")
    for r in rows[:15]:
        print(f"  [{r[0]}] {r[1]}  ({r[3]} B)  {r[2]}")
    if len(rows) > 15:
        print(f"  ... {len(rows)-15} more in results/cleanup_candidates.csv")
    print(f"REVIEW (identical files with no protected twin, never moved): {len(review)} groups")
    for grp in review[:5]:
        print("  review:", " | ".join(grp[:4]))

    with open("results/cleanup_candidates.csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(["category", "path", "reason", "bytes", "sha256"]); w.writerows(rows)
        for grp in review:
            w.writerow(["REVIEW", " | ".join(grp), "identical content, no protected twin", "", ""])

    if not apply:
        print("dry run only: nothing moved. Apply with: python3 cleanup.py --apply"); return

    ts = time.strftime("%Y%m%d_%H%M%S")
    new = not os.path.exists("results/cleanup_manifest.csv")
    with open("results/cleanup_manifest.csv", "a", newline="") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["timestamp", "category", "path", "reason", "bytes", "sha256"])
        for cat, rel, reason, size, digest in rows:
            dst = os.path.join(".trash", ts, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.move(os.path.join(ROOT, rel), dst)
            w.writerow([ts, cat, rel, reason, size, digest])
    print(f"moved {len(rows)} items to .trash/{ts}/ . Restore with: python3 cleanup.py --restore {ts}")
    print("Nothing is permanently deleted until you run: python3 cleanup.py --purge")


if __name__ == "__main__":
    main()
